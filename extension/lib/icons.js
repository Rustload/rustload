/** Builds a Lucide icon as an SVG element (no innerHTML, CSP-friendly). */
export function icon(name, { size = 16, strokeWidth = 2, className = '' } = {}) {
  const svg = document.createElementNS(SVG_NS, 'svg')
  const attrs = {
    width: size,
    height: size,
    viewBox: '0 0 24 24',
    fill: 'none',
    stroke: 'currentColor',
    'stroke-width': strokeWidth,
    'stroke-linecap': 'round',
    'stroke-linejoin': 'round',
    'aria-hidden': 'true',
    focusable: 'false',
    class: `icon ${className}`.trim(),
  }
  for (const [key, value] of Object.entries(attrs)) svg.setAttribute(key, String(value))
  for (const [tag, props] of ICONS[name] ?? []) {
    const child = document.createElementNS(SVG_NS, tag)
    for (const [key, value] of Object.entries(props)) child.setAttribute(key, value)
    svg.append(child)
  }
  return svg
}

/** Replaces every `<span data-icon="name" data-size="14">` placeholder below `root` with its icon. */
export function hydrateIcons(root = document) {
  for (const el of root.querySelectorAll('[data-icon]')) {
    const size = Number(el.dataset.size) || 16
    el.replaceChildren(icon(el.dataset.icon, { size, strokeWidth: Number(el.dataset.stroke) || 2 }))
    el.classList.add('icon-slot')
  }
}
